async def test_migrations_upgrade_downgrade_and_drift_detection(tmp_path):
    database = Database(f"sqlite+aiosqlite:///{tmp_path / 'migrations.db'}")
    try:
        await upgrade_database(database.engine)
        async with database.engine.begin() as connection:

            def check(sync_connection):
                config = migration_config()
                config.attributes["connection"] = sync_connection
                command.check(config)
                drift = Table(
                    "unmigrated_model", Base.metadata, Column("id", Integer, primary_key=True)
                )
                try:
                    with pytest.raises(AutogenerateDiffsDetected):
                        command.check(config)
                finally:
                    Base.metadata.remove(drift)
                command.downgrade(config, "base")
                assert inspect(sync_connection).get_table_names() == ["alembic_version"]
                command.upgrade(config, "head")
                command.check(config)

            await connection.run_sync(check)
    finally:
        await database.dispose()


async def test_request_session_commit_rollback_and_lifespan_disposal(tmp_path):
    database = Database(f"sqlite+aiosqlite:///{tmp_path / 'sessions.db'}")
    await upgrade_database(database.engine)
    app = create_app()

    @app.post("/test-session/{meeting_id}")
    async def probe(meeting_id: str, session: SessionDep):
        initial = Transition(from_status=None, to_status="pending")
        session.add(
            MeetingRow(
                id=meeting_id,
                status="pending",
                version=0,
                transitions=[initial.model_dump(mode="json")],
                updated_at=initial.at,
            )
        )
        await session.flush()
        if meeting_id == "rollback":
            raise HTTPException(status_code=409, detail="Test rollback")
        return {"ok": True}

    with (
        patch("baraza.main.Database", return_value=database),
        patch.object(
            database, "dispose", new_callable=AsyncMock, wraps=database.dispose
        ) as dispose,
    ):
        async with (
            app.router.lifespan_context(app),
            httpx.AsyncClient(
                transport=httpx.ASGITransport(app=app), base_url="http://test"
            ) as client,
        ):
            assert (await client.post("/test-session/committed")).status_code == 200
            assert (await client.post("/test-session/rollback")).status_code == 409
            store = SqlCaptureStore(database.engine)
            assert (await store.get("committed")).status == "pending"
            with pytest.raises(ValueError, match="Unknown"):
                await store.get("rollback")
        dispose.assert_awaited_once()
    await database.dispose()


async def test_minutes_read_endpoint_uses_shared_database(tmp_path):
    from baraza.core.meetings import MeetingStatus
    from baraza.core.minute_versions import MinutesService
    from baraza.core.minutes import Minutes

    database = Database(f"sqlite+aiosqlite:///{tmp_path / 'read.db'}")
    await upgrade_database(database.engine)
    store = SqlCaptureStore(database.engine)
    await store.create("m1")
    await store.transition("m1", MeetingStatus.PROCESSING)
    content = Minutes(summary="Fictional summary")
    async with database.sessions() as session, session.begin():
        await MinutesService(session).create_draft(
            "m1",
            content,
            actor="generator",
            template="standard",
            model_name="fake",
            prompt_version="v1",
        )
    app = create_app()
    try:
        with patch("baraza.main.Database", return_value=database):
            async with (
                app.router.lifespan_context(app),
                httpx.AsyncClient(
                    transport=httpx.ASGITransport(app=app), base_url="http://test"
                ) as client,
            ):
                response = await client.get("/meetings/m1/minutes/stored")
                assert response.status_code == 200
                assert response.json() == content.model_dump(mode="json")
                assert response.headers["etag"] == '"1"'
                assert (await client.get("/meetings/missing/minutes/stored")).status_code == 404
    finally:
        await database.dispose()
