"use client";

import { useEffect, useState, type ReactNode } from "react";
import { getMinutes } from "@/lib/api/meetings";
import type { Minutes } from "@/lib/api/types";

const NOT_SPECIFIED = "Not specified";
const POLL_INTERVAL_MS = 3000;

export function MinutesPanel({ meetingId, ready }: { meetingId: string; ready: boolean }) {
  const [minutes, setMinutes] = useState<Minutes | null>(null);
  const [error, setError] = useState(false);
  const loaded = minutes !== null;

  useEffect(() => {
    if (!ready || loaded) return;
    let cancelled = false;

    async function load() {
      try {
        const result = await getMinutes(meetingId);
        if (cancelled) return;
        setMinutes(result);
        setError(false);
      } catch {
        if (!cancelled) setError(true);
      }
    }

    // Minutes can take a while to generate: poll until they exist.
    void load();
    const timer = setInterval(load, POLL_INTERVAL_MS);
    return () => {
      cancelled = true;
      clearInterval(timer);
    };
  }, [meetingId, ready, loaded]);

  if (!ready) return null;

  return (
    <section aria-labelledby="minutes-title" className="flex flex-col gap-4">
      <h2 id="minutes-title" className="text-lg font-semibold">
        Minutes
      </h2>
      {error && (
        <p role="alert" className="text-sm text-red-600">
          Cannot load the minutes. Retrying…
        </p>
      )}
      {!minutes ? (
        <p className="text-sm text-zinc-500">Generating the minutes…</p>
      ) : (
        <>
          <p>{minutes.summary}</p>
          <Section title="Topics" empty={minutes.topics.length === 0}>
            {minutes.topics.map((t) => (
              <li key={t.title}>
                <strong>{t.title}</strong>: {t.summary}
              </li>
            ))}
          </Section>
          <Section title="Decisions" empty={minutes.decisions.length === 0}>
            {minutes.decisions.map((d) => (
              <li key={d.text}>{d.text}</li>
            ))}
          </Section>
          <Section title="Actions" empty={minutes.actions.length === 0}>
            {minutes.actions.map((a) => (
              <li key={a.text}>
                {a.text} — owner: {a.owner ?? NOT_SPECIFIED}, due: {a.due_date ?? NOT_SPECIFIED}
              </li>
            ))}
          </Section>
          <Section title="Open points" empty={minutes.open_points.length === 0}>
            {minutes.open_points.map((p) => (
              <li key={p.text}>{p.text}</li>
            ))}
          </Section>
          <p className="text-xs text-zinc-500">Draft generated by AI. Review it before sharing.</p>
        </>
      )}
    </section>
  );
}

function Section({
  title,
  empty,
  children,
}: {
  title: string;
  empty: boolean;
  children: ReactNode;
}) {
  return (
    <div>
      <h3 className="text-sm font-medium">{title}</h3>
      {empty ? (
        <p className="text-sm text-zinc-500">{NOT_SPECIFIED}</p>
      ) : (
        <ul className="list-disc pl-5 text-sm">{children}</ul>
      )}
    </div>
  );
}
